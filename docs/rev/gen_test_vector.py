#!/usr/bin/env python3
"""Generate the test vector embedded in prpr/src/record.rs's unit test.

Uses synthetic values only (no real account data), so it is safe to commit.
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from encode_upload import build_record, custom_enc, encode_token, deflate_raw, make_payload  # noqa: E402

PLAYER_ID = 1000001
CHART_ID = 12345
VARIANCE = 0.006464875507526675
MAX_COMBO = 135
COUNTS = (182, 4, 0, 19)
SPEED_X100 = 100
NUM_OF_NOTES = 205
CHART_BYTES = b"phira-test-chart"


def main() -> None:
    chart_sha = hashlib.sha256(CHART_BYTES).digest()
    rec = build_record(
        player_id=PLAYER_ID,
        chart_id=CHART_ID,
        variance=VARIANCE,
        max_combo=MAX_COMBO,
        counts=COUNTS,
        speed_x100=SPEED_X100,
        chart_sha256=chart_sha,
        num_of_notes=NUM_OF_NOTES,
    )
    cipher = custom_enc(rec)
    payload = make_payload(rec)
    token = encode_token(rec)
    assert len(rec) == 92 and len(cipher) == 96 and len(payload) == 128

    def hexwrap(b: bytes, per: int = 16) -> list[str]:
        return [b[i : i + per].hex() for i in range(0, len(b), per)]

    print(f"// synthetic test vector, generated by docs/rev/gen_test_vector.py")
    print(f"// chart_bytes = {CHART_BYTES!r}")
    print(f"// chart_sha256 = {chart_sha.hex()}")
    print()
    for name, data in (("RECORD_HEX", rec), ("CIPHER_HEX", cipher), ("PAYLOAD_HEX", payload)):
        print(f"const {name}: &[&str] = &[")
        for i, line in enumerate(hexwrap(data)):
            print(f'    "{line}",' + ("" if i * 16 + 16 < len(data) else ""))
        print("];")
    print()
    print(f"// token (base64) = {token}")
    print(f"// token bytes hex = {deflate_raw(payload, 0).hex()}")


if __name__ == "__main__":
    main()
